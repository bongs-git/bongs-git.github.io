import assert from 'node:assert/strict';
const memory = new Map();
globalThis.localStorage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value), removeItem: key => memory.delete(key) };
const draw = await import('../js/draw.js');
const now = Date.now();
const a = { t: now - 300000, p: 100 }, b = { t: now, p: 102 };
for (const type of ['line', 'rect', 'ray', 'level']) {
  draw.startDrawingEdit('QQQ');
  const item = draw.addDrawing('QQQ', type === 'level' ? { type, p: 100 } : { type, a, b, day: now });
  draw.finishDrawingEdit('QQQ');
  assert(draw.drawingsFor('QQQ').some(d => d.id === item.id));
  assert(draw.undoDrawing('QQQ'));
  assert(!draw.drawingsFor('QQQ').some(d => d.id === item.id));
}
console.log('PASS each drawing tool undoes one completed operation');
const line = draw.addDrawing('SPY', { type: 'line', a: { ...a }, b: { ...b }, day: now });
draw.startDrawingEdit('SPY'); line.a.p = 155; draw.finishDrawingEdit('SPY', false);
assert.equal(draw.drawingsFor('SPY')[0].a.p, 100);
console.log('PASS cancelled touch movement restores the persisted drawing');
const profile = draw.drawingProfile();
draw.removeDrawing('SPY', line.id);
draw.mergeDrawings(profile);
assert.equal(draw.drawingsFor('SPY').length, 0);
const deleted = draw.drawingProfile();
draw.undoDrawing('SPY');
assert(draw.drawingProfile().items[line.id].updatedAt > deleted.items[line.id].updatedAt);
draw.mergeDrawings(deleted);
assert.equal(draw.drawingsFor('SPY').length, 1);
const remote = { version: 1, items: { elsewhere: { id: 'elsewhere', type: 'ray', symbol: 'IWM', a, updatedAt: now + 10 } } };
draw.mergeDrawings(remote);
assert.equal(draw.drawingsFor('IWM').length, 1);
assert.equal(draw.drawingsFor('SPY').length, 1);
draw.reloadDrawings();
assert.equal(draw.drawingsFor('IWM')[0].type, 'ray');
console.log('PASS merging retains independent drawings and deletion markers, and undo survives a remote merge');
const { relay } = await import('../js/relay.js');
const { initDataStatus } = await import('../js/data-status.js');
const quoteTime = new Date(now - 60000).toISOString();
relay.snapshot = async () => ({ quotes: [{ symbol: 'QQQ', ok: true, source: 'TradingView bridge', delay: 0, prevClose: 0, timestamp: quoteTime }] });
relay.bars = async () => ({ bars: { QQQ: { source: 'TradingView bridge', delay: 0, session: '2026-11-19', bars: [[960, 100, 101, 99, 100, 10]] } } });
relay.chain = async () => { throw new Error('upstream 403'); };
const app = { markDirty() {}, feed: { status: { mode: 'delayed' }, syms: new Map(), quote: () => ({ prevClose: 0 }) } };
initDataStatus(app);
await relay.snapshot(['QQQ']); await relay.bars(['QQQ']);
assert.equal(app.marketData.label('QQQ', 'quote', now).text, 'TradingView, live');
assert.match(app.marketData.label('QQQ', 'quote', now + 120000).text, /last candle/);
assert.equal(app.marketData.changeKnown('QQQ'), false);
await assert.rejects(relay.chain('QQQ'));
